import SwiftUI

/// Aliaro's typographic scale.
enum ALITypography {
    static let displayLarge = Font.system(size: 48, weight: .black, design: .rounded)
    static let displayMedium = Font.system(size: 34, weight: .black, design: .rounded)
    static let headlineLarge = Font.system(size: 26, weight: .bold, design: .rounded)
    static let headlineMedium = Font.system(size: 21, weight: .bold, design: .rounded)
    static let titleLarge = Font.system(size: 17, weight: .semibold, design: .rounded)
    static let bodyLarge = Font.system(size: 16, weight: .regular)
    static let bodyMedium = Font.system(size: 14, weight: .regular)
    static let labelLarge = Font.system(size: 13, weight: .medium)
}
